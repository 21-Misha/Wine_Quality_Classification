# Import Library
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import zipfile
import os
import joblib

from sklearn.model_selection import train_test_split
from sklearn.model_selection import StratifiedKFold, cross_val_score, cross_val_predict

from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline

from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier

from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix
)

"""Mengimpor library yang diperlukan untuk proses pengolahan data, visualisasi, pembuatan model klasifikasi, dan evaluasi hasil prediksi.

### Extract Dataset
"""

# Ekstraksi dataset
with zipfile.ZipFile('/content/Data UTS.zip', 'r') as zip_ref:
    zip_ref.extractall('/content/dataset')

# Melihat isi folder
print(os.listdir('/content/dataset'))

"""Mengekstrak file ZIP agar ketiga dataset dapat dibaca dan digunakan dalam proses analisis.

### Membaca Dataset
"""

# Membaca dataset training
df_train = pd.read_csv(
    '/content/dataset/data_training.csv'
)

# Membaca dataset testing
df_test = pd.read_csv(
    '/content/dataset/data_testing.csv'
)

# Membaca template hasil prediksi
df_template = pd.read_csv(
    '/content/dataset/hasilprediksi_3digitNIMterakhir.csv',
    sep=';'
)

# Menampilkan ukuran dataset
print("Ukuran Data Training:", df_train.shape)
print("Ukuran Data Testing:", df_test.shape)
print("Ukuran Template:", df_template.shape)

# Menampilkan beberapa data
display(df_train.head())
display(df_test.head())
display(df_template.head())

"""Membaca file data training, data testing, dan template hasil prediksi menggunakan Pandas. Selanjutnya, menampilkan ukuran dan beberapa baris data untuk melihat struktur masing-masing dataset.

### Informasi Dataset
"""

# Informasi data training
print("Informasi Data Training")
df_train.info()

# Informasi data testing
print("\nInformasi Data Testing")
df_test.info()

# Statistik deskriptif
display(df_train.describe())

"""Melihat informasi dataset, seperti jumlah data, nama kolom, tipe data, dan statistik deskriptif. Tahap ini dilakukan untuk mengetahui karakteristik data sebelum masuk ke proses pengolahan.

### Distribusi Variabel Target
"""

# Menghitung jumlah setiap kategori quality
print(df_train['quality'].value_counts().sort_index())

# Visualisasi distribusi quality
plt.figure(figsize=(8, 5))

sns.countplot(
    data=df_train,
    x='quality'
)

plt.title('Distribusi Kualitas Wine')
plt.xlabel('Quality')
plt.ylabel('Jumlah Data')
plt.show()

"""Berdasarkan grafik, kualitas wine paling banyak berada pada kategori quality 5 dan 6, sedangkan kategori 3 dan 8 memiliki jumlah data paling sedikit. Hal ini menunjukkan bahwa distribusi kelas belum seimbang karena sebagian besar data terkonsentrasi pada kualitas 5 dan 6. Kondisi tersebut perlu diperhatikan dalam proses pembangunan model klasifikasi.

## 2. Pembersihan Data

### Pemeriksaan Missing Value
"""

# Missing values pada data training
print("Missing Values Data Training:")
print(df_train.isnull().sum())

# Missing values pada data testing
print("\nMissing Values Data Testing:")
print(df_test.isnull().sum())

# Total missing values
print("\nTotal Missing Training:",
      df_train.isnull().sum().sum())

print("Total Missing Testing:",
      df_test.isnull().sum().sum())

"""Memeriksa apakah terdapat nilai kosong pada dataset training dan testing. Pemeriksaan dilakukan pada setiap kolom untuk memastikan data siap digunakan.

### Penanganan Missing Value
"""

# Membuat imputasi median
imputer = SimpleImputer(strategy='median')

print("Metode penanganan missing values: Median")

"""Menyiapkan metode imputasi menggunakan nilai median untuk menangani data kosong. Metode ini diterapkan melalui Pipeline agar proses preprocessing dapat berjalan bersamaan dengan pelatihan model.

### Pemeriksaan Duplikasi Data
"""

# Pemeriksaan data duplikat
print("Duplikasi Data Training:",
      df_train.duplicated().sum())

print("Duplikasi Data Testing:",
      df_test.duplicated().sum())

"""Memeriksa apakah terdapat baris data yang memiliki nilai sama atau duplikat pada dataset training dan testing.

### Memisahkan Fitur dan Target
"""

# Memisahkan fitur dan target
X = df_train.drop(
    columns=['quality', 'Id']
)

y = df_train['quality']

# Memisahkan fitur data testing
X_test = df_test.drop(
    columns=['Id']
)

# Menyimpan ID data testing
test_id = df_test['Id']

print("Jumlah Fitur:", X.shape[1])
print("Jumlah Data Training:", X.shape[0])
print("Jumlah Data Testing:", X_test.shape[0])

"""Memisahkan variabel prediktor dan variabel target. Kolom quality menjadi target yang akan diprediksi, sedangkan kolom Id tidak digunakan dalam pemodelan karena hanya berfungsi sebagai identitas data.

## 3. Pembuatan Model

### Pembagian data
"""

# Membuat 5-Fold Stratified Cross Validation
skf = StratifiedKFold(
    n_splits=5,
    shuffle=True,
    random_state=42
)

print("Jumlah Fold:", skf.get_n_splits())
print("Metode: Stratified 5-Fold Cross Validation")

"""Membagi dataset training menjadi 5 bagian menggunakan Stratified K-Fold Cross Validation. Setiap bagian akan digunakan secara bergantian sebagai data validasi, sedangkan empat bagian lainnya digunakan untuk pelatihan model.

### Pembuatan dan Pengujian Model
"""

# Inisialisasi algoritma
models = {
    'Decision Tree': DecisionTreeClassifier(
        random_state=42,
        class_weight='balanced'
    ),

    'Random Forest': RandomForestClassifier(
        n_estimators=300,
        random_state=42,
        class_weight='balanced'
    )
}

# Menyimpan hasil evaluasi
results = {}

for name, model in models.items():

    # Membuat pipeline
    pipeline = Pipeline([
        ('imputer', SimpleImputer(strategy='median')),
        ('classifier', model)
    ])

    # Melakukan 5-Fold Cross Validation
    scores = cross_val_score(
        pipeline,
        X,
        y,
        cv=skf,
        scoring='accuracy'
    )

    # Menghitung rata-rata dan standar deviasi
    mean_accuracy = scores.mean()
    std_accuracy = scores.std()

    # Menyimpan hasil
    results[name] = {
        'model': pipeline,
        'scores': scores,
        'mean_accuracy': mean_accuracy,
        'std_accuracy': std_accuracy
    }

    print(f"\nModel: {name}")

    for i, score in enumerate(scores, 1):
        print(f"Fold {i}: {score:.4f}")

    print(f"Rata-rata Akurasi: {mean_accuracy:.4f}")
    print(f"Standar Deviasi: {std_accuracy:.4f}")

"""Melakukan pengujian terhadap Decision Tree dan Random Forest menggunakan 5-Fold Cross Validation. Setiap model diuji sebanyak lima kali, kemudian nilai akurasi dari seluruh fold dihitung rata-ratanya untuk mengetahui performa masing-masing model.

### Perbandingan Performa model
"""

# Membuat tabel perbandingan
comparison = pd.DataFrame([
    {
        'Model': name,
        'Rata-rata Accuracy': result['mean_accuracy'],
        'Standar Deviasi': result['std_accuracy']
    }
    for name, result in results.items()
])

comparison = comparison.sort_values(
    by='Rata-rata Accuracy',
    ascending=False
)

display(comparison)

"""Membandingkan rata-rata akurasi dan standar deviasi dari kedua model. Model dengan rata-rata akurasi tertinggi dipilih sebagai model terbaik, sedangkan standar deviasi digunakan untuk melihat variasi hasil akurasi antar-fold.

### Pemilihan Model Terbaik
"""

# Memilih model berdasarkan rata-rata akurasi tertinggi
best_model_name = max(
    results,
    key=lambda x: results[x]['mean_accuracy']
)

best_model = results[best_model_name]['model']

print("Model Terbaik:", best_model_name)

print(
    "Rata-rata Akurasi:",
    results[best_model_name]['mean_accuracy']
)

print(
    "Standar Deviasi:",
    results[best_model_name]['std_accuracy']
)

"""Menentukan model terbaik berdasarkan nilai rata-rata akurasi tertinggi dari lima percobaan. Model terpilih selanjutnya digunakan untuk evaluasi lebih lanjut dan prediksi data testing. Model terbaik yang diperoleh yaitu Random Forest dengan rata-rata akurasi 0.6464912280701753 dan Standar devisiasi 0.02991241579914318

### Evaluasi Model
"""

# Prediksi menggunakan 5-Fold Cross Validation
y_pred = cross_val_predict(
    best_model,
    X,
    y,
    cv=skf
)

# Menghitung akurasi
accuracy = accuracy_score(y, y_pred)

print("Model Terbaik:", best_model_name)
print("Accuracy:", accuracy)
print("Accuracy (%):", accuracy * 100)

# Classification Report
print("\nClassification Report:")
print(
    classification_report(
        y,
        y_pred,
        zero_division=0
    )
)

# Confusion Matrix
cm = confusion_matrix(y, y_pred)

plt.figure(figsize=(8, 6))

sns.heatmap(
    cm,
    annot=True,
    fmt='d',
    cmap='Blues'
)

plt.title('Confusion Matrix - 5 Fold Cross Validation')
plt.xlabel('Predicted Label')
plt.ylabel('Actual Label')

plt.show()

"""Mengevaluasi model terbaik menggunakan hasil prediksi dari lima fold. Evaluasi dilakukan menggunakan accuracy, precision, recall, F1-score, dan confusion matrix untuk mengetahui kemampuan model dalam mengklasifikasikan setiap kategori kualitas wine. Berdasarkan confusion matrix, model mampu mengklasifikasikan sebagian besar data dengan benar, terutama pada kategori quality 5 dan 6. Namun, masih terdapat kesalahan prediksi, khususnya antara kategori quality 5 dan 6. Dari total 857 data, sebanyak 554 data berhasil diklasifikasikan dengan tepat, sehingga menghasilkan akurasi sebesar 64,64%. Hal ini menunjukkan bahwa model sudah cukup mampu mengenali kualitas wine, tetapi masih mengalami kesulitan dalam membedakan beberapa kategori yang berdekatan.

### Menyimpan Model
"""

# Melatih model terbaik menggunakan seluruh data training
best_model.fit(X, y)

# Menyimpan model
joblib.dump(
    best_model,
    '/content/model_wine_quality.pkl'
)

print("Model terbaik berhasil dilatih dan disimpan!")

"""Melatih kembali model terbaik menggunakan seluruh 857 data training. Setelah proses pelatihan selesai, model disimpan dalam format .pkl menggunakan Joblib agar dapat digunakan untuk memprediksi data testing.

## 4. Prediksi Data Uji

### Melatih Model dengan 5-Fold Cross Validation
"""

from sklearn.base import clone

# Menyiapkan penyimpanan model
fold_models = []

# Melatih model pada setiap fold
for fold, (train_idx, val_idx) in enumerate(skf.split(X, y), 1):

    # Membagi data berdasarkan fold
    X_fold_train = X.iloc[train_idx]
    y_fold_train = y.iloc[train_idx]

    # Membuat salinan model terbaik
    fold_model = clone(best_model)

    # Melatih model
    fold_model.fit(X_fold_train, y_fold_train)

    # Menyimpan model
    fold_models.append(fold_model)

    print(f"Model Fold {fold} berhasil dilatih!")

print("\nTotal model yang dilatih:", len(fold_models))

"""Melatih model terbaik sebanyak lima kali menggunakan pembagian data yang berbeda pada setiap fold. Setiap model dilatih menggunakan empat bagian data training dan satu bagian lainnya digunakan sebagai validasi. Kelima model kemudian disimpan untuk digunakan dalam proses prediksi data testing.

### Prediksi Data Testing pada Setiap Fold
"""

# Menyimpan hasil prediksi setiap fold
predictions = []

for i, model in enumerate(fold_models, 1):

    # Melakukan prediksi data testing
    y_pred_test = model.predict(X_test)

    # Menyimpan hasil prediksi
    predictions.append(y_pred_test)

    print(f"Prediksi Fold {i} selesai!")

# Menggabungkan hasil prediksi
predictions = np.array(predictions)

# Membuat tabel hasil prediksi setiap fold
df_perbandingan = pd.DataFrame(
    predictions.T,
    columns=[
        'Fold 1',
        'Fold 2',
        'Fold 3',
        'Fold 4',
        'Fold 5'
    ]
)

# Menambahkan ID
df_perbandingan.insert(0, 'Id', test_id.values)

# Menampilkan hasil
display(df_perbandingan.head(20))

print("\nJumlah data:", len(df_perbandingan))

"""Melakukan prediksi terhadap seluruh data testing menggunakan lima model hasil Cross Validation. Hasil prediksi setiap model ditampilkan dalam tabel untuk melihat perbedaan klasifikasi pada masing-masing fold

### Menentukan Hasil Prediksi dengan Majority Voting
"""

from scipy.stats import mode

# Menentukan prediksi berdasarkan voting mayoritas
y_test_pred = mode(
    predictions,
    axis=0,
    keepdims=False
).mode

# Menampilkan hasil prediksi
df_prediksi = pd.DataFrame({
    'Id': test_id,
    'Quality': y_test_pred
})

display(df_prediksi.head(10))

print("Total data diprediksi:", len(df_prediksi))

"""Menggabungkan hasil prediksi dari kelima model menggunakan metode majority voting. Kategori quality yang paling banyak dipilih oleh kelima model akan menjadi hasil prediksi akhir untuk setiap data testing.

### Memasukkan Hasil ke Template
"""

# Memastikan ID sesuai dengan dataset testing
assert df_template['Id'].equals(df_test['Id']), \
    "Urutan ID tidak sesuai!"

# Memasukkan hasil prediksi
df_template['Quality'] = y_test_pred

# Menampilkan hasil
display(df_template.head(10))

print("Jumlah data:", len(df_template))

"""Memasukkan hasil prediksi akhir ke dalam template yang telah disediakan. Pemeriksaan ID dilakukan untuk memastikan hasil prediksi sesuai dengan urutan data testing.

### Menyimpan Hasil Prediksi
"""

# Menyimpan hasil prediksi
df_template.to_csv(
    '/content/hasil_prediksi.csv',
    sep=';',
    index=False
)

print("File hasil_prediksi.csv berhasil disimpan!")

"""Menyimpan hasil prediksi ke dalam file CSV dengan nama hasil_prediksi.csv. File tersebut berisi ID dan kategori quality hasil klasifikasi.

### Menyimpan Model
"""

# Menyimpan kelima model
joblib.dump(
    fold_models,
    '/content/model_wine_quality_5fold.pkl'
)

print("Kelima model berhasil disimpan!")

